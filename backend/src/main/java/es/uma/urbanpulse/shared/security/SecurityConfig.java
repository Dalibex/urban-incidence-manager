package es.uma.urbanpulse.shared.security;

import jakarta.servlet.DispatcherType;
import org.springframework.boot.autoconfigure.condition.ConditionalOnWebApplication;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.core.annotation.Order;
import org.springframework.http.HttpMethod;
import org.springframework.security.config.annotation.web.builders.HttpSecurity;
import org.springframework.security.config.annotation.web.configurers.AbstractHttpConfigurer;
import org.springframework.security.config.http.SessionCreationPolicy;
import org.springframework.security.web.SecurityFilterChain;

/**
 * Every request needs a valid access token ({@code Authorization: Bearer}) except the public paths
 * below. The roles of each operation of the API are checked here too, in the filters, by {@link
 * ApiAuthorizationRules}: the endpoint × role matrix of {@code docs/security.md}.
 *
 * <p>Only in a web application: a one-off process such as {@code bootstrap-admin} starts no web
 * server, receives no requests and has no {@code HttpSecurity} to build the chains with.
 */
@Configuration
@ConditionalOnWebApplication(type = ConditionalOnWebApplication.Type.SERVLET)
class SecurityConfig {

    // Public API documentation (docs/api.md, section 5): the contract, Swagger UI and the
    // description generated by springdoc.
    private static final String[] API_DOCS_PATHS = {
        "/openapi.yml", "/swagger-ui.html", "/swagger-ui/**", "/v3/api-docs/**"
    };

    // Operations of the contract marked with `security: []`: sign-up, sign-in, refresh, the
    // password change and the second step of a staff sign-in (#57).
    private static final String[] PUBLIC_API_POSTS = {
        "/api/v1/registrations",
        "/api/v1/sessions",
        "/api/v1/sessions/refresh",
        "/api/v1/password-changes",
        "/api/v1/mfa-enrollments",
        "/api/v1/mfa-verifications"
    };

    /**
     * The public operations have their own chain, without the bearer token filter. In the main
     * chain that filter rejects any {@code Authorization: Bearer} it cannot validate before {@code
     * permitAll} is checked, so a client that sends its expired access token along with the refresh
     * request would get {@code 401} and lose the session.
     */
    @Bean
    @Order(1)
    SecurityFilterChain publicApiFilterChain(
            HttpSecurity http, SecurityProblemResponses problemResponses) throws Exception {
        http.securityMatchers(
                        matchers -> matchers.requestMatchers(HttpMethod.POST, PUBLIC_API_POSTS))
                .authorizeHttpRequests(auth -> auth.anyRequest().permitAll());
        return statelessWithProblemResponses(http, problemResponses).build();
    }

    @Bean
    @Order(2)
    SecurityFilterChain apiFilterChain(HttpSecurity http, SecurityProblemResponses problemResponses)
            throws Exception {
        http.authorizeHttpRequests(
                        auth -> {
                            // A 400, 404 or 500 is rendered in a second, internal dispatch to
                            // /error. The original request was already authorized; without this
                            // line an anonymous caller would get 401 instead of the real error.
                            auth.dispatcherTypeMatchers(DispatcherType.ERROR).permitAll();
                            auth.requestMatchers("/actuator/health/**").permitAll();
                            // Read by Prometheus without a token. It is only reachable inside the
                            // Compose network or on 127.0.0.1: nginx does not proxy /actuator in
                            // the deployment.
                            auth.requestMatchers("/actuator/prometheus").permitAll();
                            auth.requestMatchers(API_DOCS_PATHS).permitAll();
                            ApiAuthorizationRules.authorize(auth);
                            auth.anyRequest().authenticated();
                        })
                .oauth2ResourceServer(
                        resourceServer ->
                                resourceServer
                                        .jwt(
                                                jwt ->
                                                        jwt.jwtAuthenticationConverter(
                                                                new AuthenticatedUserConverter()))
                                        .authenticationEntryPoint(problemResponses)
                                        .accessDeniedHandler(problemResponses));
        return statelessWithProblemResponses(http, problemResponses).build();
    }

    private static HttpSecurity statelessWithProblemResponses(
            HttpSecurity http, SecurityProblemResponses problemResponses) throws Exception {
        return http.exceptionHandling(
                        exceptions ->
                                exceptions
                                        .authenticationEntryPoint(problemResponses)
                                        .accessDeniedHandler(problemResponses))
                // Each request carries its token (Twelve-Factor VI): no HTTP session.
                .sessionManagement(
                        session -> session.sessionCreationPolicy(SessionCreationPolicy.STATELESS))
                // CSRF abuses credentials the browser sends by itself (cookies). A bearer token is
                // only sent when the client adds it, so there is nothing to forge.
                .csrf(AbstractHttpConfigurer::disable);
    }
}

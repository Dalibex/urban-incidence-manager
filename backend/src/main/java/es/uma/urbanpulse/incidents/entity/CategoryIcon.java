package es.uma.urbanpulse.incidents.entity;

/**
 * Which icon represents a category on the map and in the dashboard (#267). The clients map each
 * value to a drawing of their own icon set; a category without one gets their generic icon.
 */
public enum CategoryIcon {
    STREET_LIGHTING,
    PAVEMENT,
    WASTE,
    URBAN_FURNITURE,
    PARKS,
    SIGNAGE
}
